"""Exercise the local explorer without external requests or real customer data.

Run: python3 work/review-complete-explorer.py
Screenshots and the report are written to /tmp/e-invoice-complete-explorer-review.
"""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

SOURCE = Path(__file__).with_name('e-invoice-complete-explorer.html')
OUT = Path('/tmp/e-invoice-complete-explorer-review')
OUT.mkdir(exist_ok=True)
checks, errors, network = [], [], []

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1100}, timezone_id='Europe/London')
    page.set_default_timeout(4000)
    page.on('pageerror', lambda error: errors.append(str(error)))
    def abort_request(route):
        network.append(route.request.url)
        route.abort()
    page.route('http://**/*', abort_request)
    page.route('https://**/*', abort_request)

    def fresh():
        page.goto(SOURCE.resolve().as_uri())
        page.locator('.hub-nav-button[data-view="onboarding"]').click()
        page.locator('#hub-onboard-outcome').evaluate('(n) => n.closest("details").open = true')

    def tab(name):
        page.locator('.hub-nav-button[data-view="switch"]').click()
        page.locator(f'[data-settings-tab="{name}"]').click()

    def onboard(route='sage', direction='both', payments=False):
        page.locator(f'input[name="hub-start-route"][value="{route}"]').check()
        page.locator('#hub-onboard-directions').select_option(direction)
        if payments:
            page.locator('#hub-payments-next').check()
        page.locator('#hub-onboard-validate').click()
        expect(page.locator('#hub-onboard-status')).to_contain_text('Ready ·')
        expect(page.locator('#hub-current-routes')).to_contain_text('Not activated')
        page.locator('#hub-onboard-activate').click()

    def prepare(provider, direction='both'):
        tab('platforms')
        page.locator('#hub-connect-provider').select_option(provider)
        page.locator('#hub-connect-direction').select_option(direction)
        page.locator('#hub-connect-validate').click()
        expect(page.locator('#hub-connection-status')).to_contain_text('Ready to save')
        page.locator('#hub-connect-save').click()
        expect(page.locator('#hub-connection-status')).to_contain_text('Prepared')

    def review(target, scope='both'):
        page.locator('#hub-change-target').select_option(target)
        page.locator('#hub-change-direction').select_option(scope)
        page.locator('#hub-change-review').click()

    def enable_payments():
        tab('payments')
        page.locator('details').filter(has=page.locator('#hub-pas-country')).evaluate('(n) => n.open = true')
        page.locator('#hub-pas-country').check()
        if page.locator('#hub-payment-terms').is_enabled():
            page.locator('#hub-payment-terms').click()
            expect(page.locator('#hub-payment-terms-dialog')).to_be_visible()
            page.locator('#hub-payment-terms-dialog button').click()
            page.locator('#hub-payment-consent').check()

    fresh()
    expect(page.locator('#hub-onboard-activate')).to_be_disabled()
    page.locator('#hub-onboard-outcome').select_option('blocked')
    page.locator('#hub-onboard-validate').click()
    expect(page.locator('#hub-onboard-status')).to_contain_text('Needs action')
    expect(page.locator('#hub-onboard-activate')).to_be_disabled()
    page.locator('#hub-onboard-outcome').select_option('pending')
    page.locator('#hub-onboard-validate').click()
    expect(page.locator('#hub-onboard-status')).to_contain_text('Pending')
    expect(page.locator('#hub-onboard-activate')).to_be_disabled()
    page.locator('#hub-onboard-outcome').select_option('ready')
    page.locator('#hub-onboard-validate').click()
    expect(page.locator('#hub-onboard-activate')).to_be_enabled()
    page.locator('#hub-onboard-company-name').fill('Synthetic Company S.L.')
    expect(page.locator('#hub-onboard-activate')).to_be_disabled()
    checks.append('Blocked, pending and changed onboarding cannot activate stale readiness')

    fresh()
    onboard(payments=True)
    expect(page.locator('[data-settings-panel="payments"]')).to_be_visible()
    expect(page.locator('#hub-current-routes')).to_have_text('Send: Sage private platform · Receive: Sage private platform')
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    enable_payments()
    page.locator('#hub-payment-email').fill('invalid-email')
    page.locator('#hub-payment-consent').check()
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    page.locator('#hub-payment-email').fill('payments@example.invalid')
    expect(page.locator('#hub-payment-consent')).not_to_be_checked()
    page.locator('#hub-payment-consent').check()
    for control in ['hub-pas-country', 'hub-pas-network', 'hub-pas-notifications', 'hub-pas-creation']:
        page.locator('#' + control).uncheck()
        expect(page.locator('#hub-payment-create')).to_be_disabled()
        page.locator('#' + control).check()
    expect(page.locator('#hub-payment-create')).to_be_enabled()
    page.locator('#hub-pas-result').select_option('pending')
    page.locator('#hub-payment-create').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('Pending')
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    page.locator('#hub-payment-reconcile').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('Pending')
    page.locator('#hub-pas-result').select_option('active')
    page.locator('#hub-payment-reconcile').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('Account created')
    expect(page.locator('#hub-change-history')).to_contain_text('PAS account request 1: active')
    assert 'request 2' not in page.locator('#hub-change-history').inner_text()
    page.screenshot(path=str(OUT / 'payments-desktop.png'), full_page=True)
    page.locator('#hub-payment-deleted').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('account.deleted')
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Sage private platform')
    checks.append('PAS consent, valid email, country, Network, notification and creation gates enforced')
    checks.append('Pending PAS request reconciles without creating a second account')
    checks.append('account.deleted disables payments and retains invoice routes')

    fresh()
    onboard(payments=True)
    enable_payments()
    page.locator('#hub-pas-result').select_option('failed')
    page.locator('#hub-payment-create').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('confirmed failure')
    expect(page.locator('#hub-payment-create')).to_be_enabled()
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Sage private platform')
    page.locator('#hub-pas-result').select_option('active')
    page.locator('#hub-payment-create').click()
    expect(page.locator('#hub-payment-status')).to_contain_text('Account created')
    checks.append('Confirmed PAS failure permits corrected retry without blocking e-invoicing')

    fresh()
    onboard('public')
    prepare('sage')
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Spanish Public Platform')
    review('sage')
    expect(page.locator('#hub-change-confirmation')).to_be_visible()
    page.locator('#hub-change-cancel').click()
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Spanish Public Platform')
    review('sage')
    page.locator('#hub-change-confirm').click()
    expect(page.locator('#hub-current-routes')).to_have_text('Send: Sage private platform · Receive: Sage private platform')
    expect(page.locator('#hub-change-history')).to_contain_text('Earlier invoices retain their original platform context')
    prepare('edicom')
    review('edicom')
    expect(page.locator('#hub-change-message')).to_contain_text('not enabled')
    expect(page.locator('#hub-change-confirmation')).to_be_hidden()
    page.screenshot(path=str(OUT / 'settings-desktop.png'), full_page=True)
    checks.append('Preparing a platform and cancelling review preserve the live route')
    checks.append('Explicit public-to-Sage activation preserves history and blocks private-to-private migration')

    fresh()
    onboard('public')
    prepare('sage', 'outbound')
    review('sage', 'both')
    expect(page.locator('#hub-change-message')).to_contain_text('not ready')
    review('sage', 'outbound')
    page.locator('#hub-change-confirm').click()
    expect(page.locator('#hub-current-routes')).to_have_text('Send: Sage private platform · Receive: Spanish Public Platform (AEAT)')
    checks.append('Direction readiness and scoped activation are enforced')

    fresh()
    onboard('public')
    prepare('sage')
    page.locator('#hub-change-timing').select_option('scheduled')
    page.locator('#hub-change-date').fill('2020-01-01T12:00')
    review('sage')
    expect(page.locator('#hub-change-message')).to_contain_text('future')
    future = page.evaluate('new Date(Date.now()+3500-new Date().getTimezoneOffset()*60000).toISOString().slice(0,19)')
    page.locator('#hub-change-date').fill(future[:-3] if future.endswith(':00') else future)
    review('sage')
    page.locator('#hub-change-confirm').click()
    expect(page.locator('#hub-change-message')).to_contain_text('Scheduled')
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Spanish Public Platform')
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Sage private platform', timeout=7000)
    checks.append('Past schedules rejected; confirmed future change applies only when due')

    fresh()
    onboard('public')
    prepare('sage')
    page.locator('#hub-change-timing').select_option('scheduled')
    page.locator('#hub-change-date').fill('2099-01-01T12:00')
    review('sage')
    page.locator('#hub-change-confirm').click()
    page.locator('#hub-change-cancel').click()
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Spanish Public Platform')
    checks.append('Confirmed scheduled change can be cancelled without changing current routes')

    fresh()
    page.locator('#hub-setup-scenario').select_option('unknown')
    page.locator('#hub-onboard-validate').click()
    expect(page.locator('#hub-onboard-status')).to_contain_text('Needs assessment')
    expect(page.locator('#hub-onboard-activate')).to_be_disabled()
    for scenario in ['public', 'private', 'sage']:
        fresh()
        page.locator('#hub-setup-scenario').select_option(scenario)
        expect(page.locator('#hub-onboard-status')).to_contain_text('Existing setup retained')
        tab('platforms')
        assert page.locator('#hub-connections-list li').count() == 1
    checks.append('Existing public, private and Sage setups reused; unknown setup needs assessment')

    fresh()
    onboard('public')
    prepare('sage')
    review('sage')
    tab('access')
    page.locator('#hub-demo-role').select_option('viewer')
    tab('platforms')
    expect(page.locator('#hub-change-confirmation')).to_be_hidden()
    expect(page.locator('#hub-connect-validate')).to_be_disabled()
    expect(page.locator('#hub-change-review')).to_be_disabled()
    tab('access')
    page.locator('#hub-demo-role').select_option('accountant')
    page.locator('#hub-demo-delegation').select_option('routes')
    tab('platforms')
    expect(page.locator('#hub-connect-validate')).to_be_enabled()
    review('sage')
    page.locator('#hub-change-confirm').click()
    enable_payments()
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    tab('access')
    page.locator('#hub-demo-payment-grant').check()
    tab('payments')
    page.locator('#hub-payment-consent').check()
    expect(page.locator('#hub-payment-create')).to_be_enabled()
    checks.append('Read-only user cannot mutate; accountant needs separate payment-service authority')

    page.locator('.hub-nav-button[data-view="onboarding"]').click()
    page.locator('[data-onboard-mode="batch"]').click()
    page.locator('#hub-batch-activate').click()
    expect(page.locator('#hub-batch-status')).to_contain_text('Not permitted')
    checks.append('Routes-only accountant cannot activate portfolio clients')

    fresh()
    onboard('public')
    tab('platforms')
    page.locator('#hub-connect-provider').select_option('other')
    page.locator('#hub-connect-validate').click()
    expect(page.locator('#hub-connection-status')).to_contain_text('Assessment required')
    expect(page.locator('#hub-connect-save')).to_be_disabled()
    page.locator('#hub-connect-provider').select_option('sage')
    page.locator('#hub-connect-validate').click()
    expect(page.locator('#hub-connect-save')).to_be_enabled()
    page.locator('#hub-connect-credential').fill('SYNTH-CHANGED-REFERENCE')
    expect(page.locator('#hub-connect-save')).to_be_disabled()
    expect(page.locator('#hub-current-routes')).to_contain_text('Send: Spanish Public Platform')
    checks.append('Unsupported providers need assessment and edited credentials invalidate readiness')

    fresh()
    onboard('sage', 'inbound')
    tab('payments')
    expect(page.locator('#hub-payment-eligibility')).to_contain_text('Activate Sage private-platform sending')
    expect(page.locator('#hub-payment-create')).to_be_disabled()
    checks.append('Receive-only setup cannot enable collection for issued invoices')

    fresh()
    onboard('sage')
    page.locator('.hub-nav-button[data-view="exchange"]').click()
    page.locator('#hub-send-route').select_option('sage')
    page.locator('#hub-route-check').click()
    page.locator('#hub-run-route-validation').click()
    expect(page.locator('#hub-validation-result-title')).to_contain_text('Sage private platform', timeout=5000)
    page.locator('#hub-route-dialog button[value="cancel"]').first.click()
    expect(page.locator('#hub-send-button')).to_be_enabled()
    page.locator('#hub-send-button').click()
    expect(page.locator('#hub-send-status')).to_contain_text('Admitted')
    page.locator('[data-exchange-mode="receive"]').click()
    expect(page.locator('#hub-inbound-readiness')).to_contain_text('Sage private platform')
    page.locator('#hub-retrieve').click()
    expect(page.locator('#hub-receive-status')).to_contain_text('Sage private platform')
    checks.append('Sage connection is reflected in sending and receiving screens')
    page.locator('[data-exchange-mode="send"]').click()
    page.locator('#hub-route-check').click()
    page.locator('#hub-run-route-validation').click()
    # A product can change identity while a check is in progress; old timers must not pass it.
    page.locator('#hub-buyer-id').evaluate('(n) => { n.value = "SYNTH-CHANGED"; n.dispatchEvent(new Event("input", {bubbles:true})); }')
    page.wait_for_timeout(2200)
    page.locator('#hub-route-dialog button[value="cancel"]').first.click()
    expect(page.locator('#hub-send-button')).to_be_disabled()
    checks.append('Changed invoice identity invalidates an in-flight route check')

    fresh()
    page.locator('.hub-nav-button[data-view="onboarding"]').focus()
    page.keyboard.press('ArrowRight')
    expect(page.locator('.hub-nav-button[data-view="exchange"]')).to_be_focused()
    expect(page.locator('#hub-view-exchange')).to_be_visible()
    page.keyboard.press('End')
    expect(page.locator('#hub-view-fields')).to_be_visible()
    page.locator('[data-field-stage="payments"]').click()
    expect(page.locator('#hub-fields-principle')).to_contain_text('not an approved POST /accounts payload')
    checks.append('Keyboard tab navigation and PAS field catalogue work')

    fresh()
    onboard('sage', payments=True)
    for width, scheme in [(1440, 'light'), (768, 'light'), (390, 'light'), (390, 'dark')]:
        page.set_viewport_size({'width': width, 'height': 1000})
        page.emulate_media(color_scheme=scheme)
        for category in ['platforms', 'payments', 'access']:
            tab(category)
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), (width, category, scheme)
        tab('payments')
        page.screenshot(path=str(OUT / f'payments-{width}-{scheme}.png'), full_page=True)
    checks.append('Settings has no page overflow at 1440, 768 and 390px, including dark mode')
    assert not errors, errors
    assert not network, network
    ids = page.locator('[id]').evaluate_all('(nodes) => nodes.map(n => n.id)')
    assert len(ids) == len(set(ids)), 'Duplicate HTML IDs'
    report = {'result': 'passed', 'checks': checks, 'browser_errors': errors, 'external_requests': network, 'published': False}
    (OUT / 'validation.json').write_text(json.dumps(report, indent=2) + '\n')
    browser.close()
print(json.dumps({'result': 'passed', 'scenario_groups': len(checks), 'report': str(OUT / 'validation.json')}))
